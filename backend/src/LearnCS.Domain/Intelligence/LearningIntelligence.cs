using LearnCS.Domain.Common;

namespace LearnCS.Domain.Intelligence;

public enum LearnerLevel { Beginner = 0, Elementary = 1, Intermediate = 2, Advanced = 3, Expert = 4 }
public enum RecommendationType { NextConcept = 0, PracticeMore = 1, Revision = 2, NextLesson = 3, Project = 4 }

/// <summary>
/// Tracks mastery of a specific concept for a specific user.
/// Updated after assessments, practice, and lesson completions.
/// </summary>
public class ConceptMastery : BaseEntity
{
    public Guid UserId { get; private set; }
    public Guid ConceptId { get; private set; }

    /// <summary>0-100 mastery score</summary>
    public decimal MasteryScore { get; private set; }

    /// <summary>0-1 confidence value (how reliable is the mastery score)</summary>
    public decimal Confidence { get; private set; }

    public DateTime LastEvaluatedAt { get; private set; } = DateTime.UtcNow;

    /// <summary>JSON: evidence sources (quiz scores, lesson completions, practice results)</summary>
    public string? EvidenceJson { get; private set; }

    public int TotalAttempts { get; private set; }
    public int CorrectAnswers { get; private set; }

    private ConceptMastery() { }

    public static ConceptMastery Create(Guid userId, Guid conceptId)
        => new ConceptMastery { UserId = userId, ConceptId = conceptId };

    /// <summary>
    /// Updates mastery based on a new evidence point (e.g. quiz score or lesson completion).
    /// Uses exponential moving average to weight recent performance more heavily.
    /// </summary>
    public void UpdateFromEvidence(decimal newScore, bool fromAssessment, string? evidenceJson = null)
    {
        TotalAttempts++;
        if (newScore >= 70) CorrectAnswers++;

        // EMA with alpha=0.3 (recent evidence counts more)
        MasteryScore = TotalAttempts == 1
            ? newScore
            : Math.Round(0.3m * newScore + 0.7m * MasteryScore, 2);

        Confidence = Math.Min(1.0m, TotalAttempts / 10.0m);
        if (fromAssessment) Confidence = Math.Min(1.0m, Confidence + 0.2m);

        LastEvaluatedAt = DateTime.UtcNow;
        EvidenceJson = evidenceJson;
        SetUpdated();
    }

    public bool IsMastered => MasteryScore >= 80 && Confidence >= 0.5m;
    public bool IsWeak => MasteryScore < 40;
}

/// <summary>
/// Snapshot of a learner's overall level, calculated from concept mastery and XP.
/// </summary>
public class LearnerLevelRecord : BaseEntity
{
    public Guid UserId { get; private set; }
    public LearnerLevel Level { get; private set; } = LearnerLevel.Beginner;
    public long XpTotal { get; private set; }
    public decimal OverallMasteryScore { get; private set; }
    public DateTime EvaluatedAt { get; private set; } = DateTime.UtcNow;
    public string? SummaryJson { get; private set; }

    private LearnerLevelRecord() { }

    public static LearnerLevelRecord Create(Guid userId)
        => new LearnerLevelRecord { UserId = userId };

    public void Update(LearnerLevel level, long xpTotal, decimal overallMastery, string? summaryJson = null)
    {
        Level = level;
        XpTotal = xpTotal;
        OverallMasteryScore = overallMastery;
        EvaluatedAt = DateTime.UtcNow;
        SummaryJson = summaryJson;
        SetUpdated();
    }
}

/// <summary>
/// A personalized recommendation generated by the intelligence engine.
/// Examples: "Learn Recursion next", "Revise Arrays, your score was low"
/// </summary>
public class LearningRecommendation : BaseEntity
{
    public Guid UserId { get; private set; }
    public RecommendationType Type { get; private set; }
    public Guid? ConceptId { get; private set; }
    public Guid? LessonId { get; private set; }
    public Guid? ProjectId { get; private set; }
    public string Reason { get; private set; } = string.Empty;
    public decimal Score { get; private set; }
    public bool IsActed { get; private set; }
    public DateTime? ActedAt { get; private set; }
    public bool IsActive { get; private set; } = true;

    private LearningRecommendation() { }

    public static LearningRecommendation Create(Guid userId, RecommendationType type, string reason,
        decimal score, Guid? conceptId = null, Guid? lessonId = null, Guid? projectId = null)
        => new LearningRecommendation
        {
            UserId = userId, Type = type, Reason = reason, Score = score,
            ConceptId = conceptId, LessonId = lessonId, ProjectId = projectId
        };

    public void MarkActed()
    {
        IsActed = true;
        ActedAt = DateTime.UtcNow;
        SetUpdated();
    }

    public void Dismiss() { IsActive = false; SetUpdated(); }
}

/// <summary>
/// Personalized learning roadmap generated for a user based on their assessment results.
/// </summary>
public class LearningRoadmap : BaseEntity
{
    public Guid UserId { get; private set; }
    public string Title { get; private set; } = string.Empty;
    public bool IsActive { get; private set; } = true;
    public Guid? BasedOnAttemptId { get; private set; }
    public string? GenerationContextJson { get; private set; }

    public ICollection<RoadmapStep> Steps { get; private set; } = new List<RoadmapStep>();

    private LearningRoadmap() { }

    public static LearningRoadmap Create(Guid userId, string title, Guid? basedOnAttemptId = null)
        => new LearningRoadmap { UserId = userId, Title = title, BasedOnAttemptId = basedOnAttemptId };

    public void Deactivate() { IsActive = false; SetUpdated(); }
}

public enum RoadmapStepStatus { Pending = 0, InProgress = 1, Completed = 2, Skipped = 3 }

public class RoadmapStep : BaseEntity
{
    public Guid RoadmapId { get; private set; }
    public Guid ConceptId { get; private set; }
    public Guid? LessonId { get; private set; }
    public int DisplayOrder { get; private set; }
    public RoadmapStepStatus Status { get; private set; } = RoadmapStepStatus.Pending;
    public string? Reason { get; private set; }
    public DateTime? CompletedAt { get; private set; }

    public LearningRoadmap? Roadmap { get; private set; }

    private RoadmapStep() { }

    public static RoadmapStep Create(Guid roadmapId, Guid conceptId, int order,
        Guid? lessonId = null, string? reason = null)
        => new RoadmapStep
        {
            RoadmapId = roadmapId, ConceptId = conceptId, DisplayOrder = order,
            LessonId = lessonId, Reason = reason
        };

    public void Complete() { Status = RoadmapStepStatus.Completed; CompletedAt = DateTime.UtcNow; SetUpdated(); }
    public void Start() { Status = RoadmapStepStatus.InProgress; SetUpdated(); }
    public void Skip() { Status = RoadmapStepStatus.Skipped; SetUpdated(); }
}
